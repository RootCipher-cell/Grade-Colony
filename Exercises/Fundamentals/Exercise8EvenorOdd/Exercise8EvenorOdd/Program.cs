Console.WriteLine("Enter 1st Integer");
int num1 = int.Parse(Console.ReadLine());
Console.WriteLine("Enter 2nd Integer");
int num2 = int.Parse(Console.ReadLine());
if (num1 % 2 == 0)
{
    Console.WriteLine("1st Integer is Even");
}
else
{
    Console.WriteLine("1st Integer is Odd");
}
if (num2 % 2 == 0)
{
    Console.WriteLine("2nd Integer is Even");
}
else
{
    Console.WriteLine("2nd Integer is Odd");
}